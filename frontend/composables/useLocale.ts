export function useLocale() {
  const locale = useState<AppLocale>('app-locale', () => 'en');

  const availableLocales = [
    { code: 'en' as const, label: 'English', flag: '/flags/us.svg' },
    { code: 'fr' as const, label: 'Français', flag: '/flags/fr.svg' },
  ];

  const isEnglish = computed(() => locale.value === 'en');
  const isFrench = computed(() => locale.value === 'fr');

  const setLocale = (value: AppLocale) => {
    locale.value = value;
    if (process.client) {
      localStorage.setItem('app_locale', value);
      document.documentElement.lang = value;
    }
  };

  const initLocale = () => {
    if (!process.client) return;

    const saved = localStorage.getItem('app_locale');
    if (saved === 'en' || saved === 'fr') {
      locale.value = saved;
    } else {
      locale.value = 'en';
      localStorage.setItem('app_locale', 'en');
    }
    document.documentElement.lang = locale.value;
  };

  onMounted(() => {
    initLocale();
  });

  const t = (key: string, params?: Record<string, string | number>) => {
    const current = translations[locale.value];
    const fallback = translations.en;
    const value = current[key] ?? fallback[key] ?? key;

    if (!params) return value;

    return value.replace(/\{(\w+)\}/g, (_match, p1) => String(params[p1] ?? `{${p1}}`));
  };

  return { locale, availableLocales, setLocale, initLocale, t, isEnglish, isFrench };
}
